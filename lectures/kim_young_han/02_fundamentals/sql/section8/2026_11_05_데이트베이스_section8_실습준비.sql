-- 인덱스 
-- 느린 검색의 원인 -> Full Table Scan
-- 인덱스가 없는 테이블에서 특정 데이터를 찾는 과정은, 특정 단어를 하나 찾기위해, 첫번 째 행부터 마지막 행까지 하나하나 검색하면서 찾아보는 것과 같음.
-- 이러한 작업 방식을 풀 테이블 스캔(Full Table Scan)이라고 부른다. 
-- 최선의 경우: 우리가 찾는 데이터가 우연히 첫 번째 행에 있다면 한 번의 비교만으로 끝난다. 
-- 최악의 경우: 우리가 찾는 데이터가 맨 마지막 행에 있거나, 아예 존재하지 않는다면 1억 번의 비교를 모두 수행해야만 결과를 알 수 있다. 
-- 풀 테이블 스캔은 빅오 표기법으로 O(n)으로 표현한다. 여기서 n은 레코드 건수를 나타내며, 레코드 수가 두 배로 증가하면 스캔 시간도 두 배로 증가한다는 의미다. 
-- 다시말하면 풀 테이블 스캔은 데이터 건 수 만큼 데이터를 탐색해야 한다는 뜻이다. 